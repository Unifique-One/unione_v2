#!/usr/bin/env bash
set -euo pipefail

ROOT=/opt/unione
LOG=$ROOT/scripts/deploy-all.log
HOSTS="cloud drive files office meet calendar contacts forms board whiteboard notes tasks projects ai id auth mail status admin api"

log() { printf '[%s] %s\n' "$(date -u +%FT%TZ)" "$*" | tee -a "$LOG"; }
warn() { log "WARN: $*"; }

need() { command -v "$1" >/dev/null 2>&1 || { log "missing command: $1"; exit 1; }; }
need podman
need curl

mkdir -p "$ROOT/secrets" "$ROOT/scripts" "$ROOT/stack"

# 1. Ensure the Traefik basic-auth htpasswd exists (bcrypt via Apache httpd utility).
if [[ ! -s "$ROOT/secrets/admin.htpasswd" ]]; then
  log "generating admin.htpasswd"
  PASSWORD=$(tr -d '\n' < "$ROOT/secrets/admin.password")
  LINE=$(podman run --rm --entrypoint htpasswd docker.io/library/httpd:2 -Bbn admin "$PASSWORD")
  printf '%s\n' "$LINE" > "$ROOT/secrets/admin.htpasswd"
  chown 65532:65532 "$ROOT/secrets/admin.htpasswd"
  chmod 600 "$ROOT/secrets/admin.htpasswd"
fi

# 2. Ensure Nextcloud admin credentials are in the env file generated by the stack subagent.
ENV_FILE=$ROOT/stack/env/nextcloud.env
if [[ -f "$ENV_FILE" ]]; then
  if ! grep -q '^NEXTCLOUD_ADMIN_USER=' "$ENV_FILE"; then
    printf 'NEXTCLOUD_ADMIN_USER=admin\n' >> "$ENV_FILE"
  fi
  if ! grep -q '^NEXTCLOUD_ADMIN_PASSWORD=' "$ENV_FILE"; then
    printf 'NEXTCLOUD_ADMIN_PASSWORD=%s\n' "$(tr -d '\n' < "$ROOT/secrets/nextcloud-admin.password")" >> "$ENV_FILE"
  fi
  chmod 600 "$ENV_FILE"
fi

# 3. Deploy the Podman stack.
log "running stack deploy"
bash "$ROOT/stack/scripts/deploy.sh"

# 4. Wait for the portal to answer through Traefik.
log "waiting for cloud.csphere.cloud via local Traefik"
for i in $(seq 1 60); do
  CODE=$(curl -s -o /dev/null -w '%{http_code}' -H 'Host: cloud.csphere.cloud' http://127.0.0.1:8080/status.php || true)
  if [[ "$CODE" == "200" ]]; then
    log "portal ready (HTTP $CODE)"
    break
  fi
  if [[ "$i" == "60" ]]; then
    warn "portal did not return 200 in time (last=$CODE)"
  fi
  sleep 5
done

# 5. Apply and verify branding.
if [[ -x "$ROOT/scripts/branding/apply-nextcloud-branding.sh" ]]; then
  log "applying Nextcloud branding"
  bash "$ROOT/scripts/branding/apply-nextcloud-branding.sh" || warn "branding script reported errors"
else
  warn "branding script not found"
fi

if [[ -x "$ROOT/scripts/branding/verify-nextcloud.sh" ]]; then
  log "verifying Nextcloud branding"
  bash "$ROOT/scripts/branding/verify-nextcloud.sh" || warn "verification script reported errors"
fi

# 6. Start Cloudflare tunnel on the same Podman network as Traefik.
TUNNEL_ENV=/etc/unione/cloudflared/tunnel.env
if [[ -s "$TUNNEL_ENV" ]]; then
  log "starting unione-cloudflared with tunnel token"
  podman rm -f unione-cloudflared >/dev/null 2>&1 || true
  podman run -d --replace --restart unless-stopped --name unione-cloudflared --network unione \
    --network-alias cloudflared \
    --env-file "$TUNNEL_ENV" \
    docker.io/cloudflare/cloudflared:2025.11.1 \
    tunnel --no-autoupdate run
else
  warn "tunnel token env missing; unione-cloudflared not started"
fi

# 7. AI is intentionally deferred by user decision; no Ollama container/model is deployed.
#    ai.csphere.cloud is routed by Traefik to the Nextcloud/Assistant interface.

# 8. Local host-based validation for every reserved hostname.
log "validating hostnames through local Traefik"
for h in $HOSTS; do
  CODE=$(curl -s -o /dev/null -w '%{http_code}' -H "Host: $h.csphere.cloud" http://127.0.0.1:8080/ || true)
  log "$h.csphere.cloud -> HTTP $CODE"
done

log "DEPLOY_ALL_DONE"
