#!/usr/bin/env bash
# UNIFIQUE ONE - direct `podman run` fallback (equivalent to the quadlets).
# Re-runs are safe: missing networks/volumes are created and every container is
# (re)started with `podman run -d --replace` under a stable name.
# The Cloudflare Tunnel connector is intentionally excluded; use
# cloudflared.container for that (tunnel/DNS changes are handled separately).
set -euo pipefail

STACK_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$STACK_DIR/env/nextcloud.env"
TRAEFIK_STATIC="/opt/unione/traefik/traefik.yml"
TRAEFIK_DYNAMIC="/opt/unione/traefik/dynamic/services.yml"
ADMIN_HTPASSWD="/opt/unione/secrets/admin.htpasswd"
BRANDING_DIR="/opt/unione/branding"
THEME_DIR="$BRANDING_DIR/nextcloud-theme/unifique"
APP_DIR="$BRANDING_DIR/nextcloud-apps/unifique_branding"
COLLABORA_DIR="$STACK_DIR/config/collabora"
STATUS_DIR="$BRANDING_DIR/integrations/services/status"
COTURN_ENV="$STACK_DIR/env/coturn.env"
COTURN_CONF="$STACK_DIR/config/coturn.conf"
NETWORK="unione"

log() { printf '[unione] %s\n' "$*"; }
die() { printf '[unione] ERROR: %s\n' "$*" >&2; exit 1; }

command -v podman >/dev/null 2>&1 || die "podman is required"
[[ -r "$ENV_FILE" ]] || die "missing $ENV_FILE"
[[ -r "$TRAEFIK_STATIC" ]] || die "missing $TRAEFIK_STATIC"
[[ -r "$TRAEFIK_DYNAMIC" ]] || die "missing $TRAEFIK_DYNAMIC"
[[ -f "$ADMIN_HTPASSWD" ]] || die "missing $ADMIN_HTPASSWD (Traefik basicAuth uses it)"
[[ -d "$STATUS_DIR" ]] || die "missing $STATUS_DIR (nginx status document root)"

# --- network ---------------------------------------------------------------
if ! podman network exists "$NETWORK" >/dev/null 2>&1; then
	log "create network $NETWORK"
	podman network create "$NETWORK"
fi

# --- volumes ---------------------------------------------------------------
for volume in unione-nextcloud unione-postgres unione-redis; do
	if ! podman volume exists "$volume" >/dev/null 2>&1; then
		log "create volume $volume"
		podman volume create "$volume"
	fi
done

# --- TURN secret and config -------------------------------------------------
mkdir -p "$STACK_DIR/env" "$STACK_DIR/config"
if [[ ! -s "$COTURN_ENV" ]]; then
	secret="$(openssl rand -hex 32 2>/dev/null || od -An -N32 -tx1 /dev/urandom | tr -d ' \n')"
	( umask 077; printf 'TURN_SECRET=%s\n' "$secret" > "$COTURN_ENV" )
	log "generated $COTURN_ENV with 0600 permissions"
fi
# shellcheck disable=SC1090
source "$COTURN_ENV"
: "${TURN_SECRET:?TURN_SECRET must be set in $COTURN_ENV}"

cat > "$COTURN_CONF" <<EOF
# Generated by deploy.sh. Rotate the secret in $COTURN_ENV, not here.
listening-port=3478
fingerprint
lt-cred-mech
use-auth-secret
static-auth-secret=$TURN_SECRET
realm=csphere.cloud
total-quota=100
bps-capacity=0
stale-nonce
no-multicast-peers
no-cli
log-file=stdout
EOF
chmod 640 "$COTURN_CONF"

# --- containers -------------------------------------------------------------
run_container() {
	local name="$1"
	shift
	if podman container exists "$name" >/dev/null 2>&1; then
		log "replace existing container $name"
	else
		log "start container $name"
	fi
	podman run -d --replace --restart unless-stopped --name "$name" --network "$NETWORK" "$@"
}

run_container unione-postgres \
	--network-alias postgres \
	-v unione-postgres:/var/lib/postgresql/data \
	--env-file "$ENV_FILE" \
	postgres:16-alpine

run_container unione-redis \
	--network-alias redis \
	-v unione-redis:/data \
	redis:7-alpine

run_container unione-nextcloud \
	--network-alias nextcloud \
	-v unione-nextcloud:/var/www/html \
	-v "$BRANDING_DIR:/mnt/branding:ro" \
	-v "$THEME_DIR:/var/www/html/themes/unifique:ro" \
	-v "$APP_DIR:/var/www/html/apps/unifique_branding:ro" \
	--env-file "$ENV_FILE" \
	nextcloud:stable-apache

run_container unione-collabora \
	--network-alias collabora \
	-e 'domain=cloud\.csphere\.cloud|drive\.csphere\.cloud' \
	-e 'extra_params=--o:ssl.enable=false' \
	-v "$COLLABORA_DIR/coolwsd.xml:/etc/coolwsd/coolwsd.xml:ro,Z" \
	-v "$COLLABORA_DIR/branding.js:/usr/share/coolwsd/browser/dist/branding.js:ro,Z" \
	-v "$COLLABORA_DIR/branding.css:/usr/share/coolwsd/browser/dist/branding.css:ro,Z" \
	-v "$COLLABORA_DIR/unione-symbol-light.png:/usr/share/coolwsd/browser/dist/images/unione-symbol-light.png:ro,Z" \
	-v "$COLLABORA_DIR/unione-symbol-dark.png:/usr/share/coolwsd/browser/dist/images/unione-symbol-dark.png:ro,Z" \
	collabora/code:latest

run_container unione-coturn \
	--network-alias turn \
	-v "$COTURN_CONF:/etc/coturn/turnserver.conf:ro" \
	coturn/coturn:latest

run_container unione-status \
	--network-alias status \
	-v "$STATUS_DIR:/usr/share/nginx/html:ro" \
	nginx:alpine

# Traefik is resolvable on the unione network as "traefik".
# The Cloudflare Tunnel ingress targets http://traefik:80.
# Host ports are bound to 127.0.0.1 only; no public 80/443 is opened.
run_container unione-traefik \
	--network-alias traefik \
	-p 127.0.0.1:8080:80 \
	-v "$TRAEFIK_STATIC:/etc/traefik/traefik.yml:ro,Z" \
	-v "$(dirname "$TRAEFIK_DYNAMIC"):/etc/traefik/dynamic:ro,Z" \
	-v "$ADMIN_HTPASSWD:/etc/traefik/admin.htpasswd:ro,Z" \
	traefik:v3.3 \
	--configFile=/etc/traefik/traefik.yml

log "done. unione-traefik origin: http://traefik:80 on network $NETWORK (host 8080:80)."
log "Cloudflare Tunnel configuration is managed separately."
